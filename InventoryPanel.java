    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    String name = txtProductName.getText().trim();
    String priceStr = jTextField3.getText().trim();
    String stockStr = jTextField2.getText().trim();

    if (name.isEmpty() || priceStr.isEmpty() || stockStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Lahat ng fields ay required.");
        return;
    }

    CategoryItem selectedCategory = (CategoryItem) cbCategory.getSelectedItem();
    SupplierItem selectedSupplier = (SupplierItem) cbSupplier.getSelectedItem();

    if (selectedCategory == null || selectedSupplier == null) {
        JOptionPane.showMessageDialog(this, "Pumili ng Category at Supplier.");
        return;
    }

    try {
        double price = Double.parseDouble(priceStr);
        int stock = Integer.parseInt(stockStr);

        String sql = "INSERT INTO products (product_name, category_id, supplier_id, unit_price, stock_quantity, is_archived) " +
                     "VALUES (?, ?, ?, ?, ?, 0)";

        try (Connection conn = ConnectDb.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, name);
            ps.setInt(2, selectedCategory.getId());
            ps.setInt(3, selectedSupplier.getId());
            ps.setDouble(4, price);
            ps.setInt(5, stock);
            ps.executeUpdate();

            loadProducts();

            if (parentDashboard != null) {
            parentDashboard.refreshSalesPanel();
             }

            txtProductName.setText("");
            jTextField3.setText("");
            jTextField2.setText("");

JOptionPane.showMessageDialog(this, "Product added successfully!");   
        }
        
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Price and Stock must be numbers only.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
int[] selectedRows = InventoryTable.getSelectedRows();

    if (selectedRows.length == 0) {
        JOptionPane.showMessageDialog(this, "Pumili muna ng product na iaarchive.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this,
        "Archive " + selectedRows.length + " selected product(s)?",
        "Confirm Archive", JOptionPane.YES_NO_OPTION);

    if (confirm != JOptionPane.YES_OPTION) return;

    String sql = "UPDATE products SET is_archived = 1 WHERE product_id = ?";

    try (Connection conn = ConnectDb.getConnection();
         PreparedStatement ps = conn.prepareStatement(sql)) {

        for (int row : selectedRows) {
            int productId = (int) InventoryTable.getValueAt(row, 0);
            ps.setInt(1, productId);
            ps.addBatch();
        }
        ps.executeBatch();

        loadProducts();

        if (parentDashboard != null) {
            parentDashboard.refreshSalesPanel();
        }

        JOptionPane.showMessageDialog(this, "Product(s) archived.");

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }       // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

