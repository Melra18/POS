    private void btnNewSupplier1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNewSupplier1ActionPerformed
Object selected = cbSupplier.getSelectedItem();   // palitan ng pangalan ng combo box mo
if (selected == null) return;
String name = selected.toString();

int confirm = JOptionPane.showConfirmDialog(this,
    "Burahin ang supplier na '" + name + "'?",
    "Confirm Delete", JOptionPane.YES_NO_OPTION);
if (confirm != JOptionPane.YES_OPTION) return;

String countSql = "SELECT s.supplier_id, COUNT(p.product_id) AS total "
                + "FROM suppliers s LEFT JOIN products p ON p.supplier_id = s.supplier_id "
                + "WHERE s.supplier_name = ? GROUP BY s.supplier_id";
String deleteSql = "DELETE FROM suppliers WHERE supplier_id = ?";

try (Connection conn = ConnectDb.getConnection();
     PreparedStatement count = conn.prepareStatement(countSql)) {

    count.setString(1, name);
    try (ResultSet rs = count.executeQuery()) {
        if (!rs.next()) return;
        int id = rs.getInt("supplier_id");
        int total = rs.getInt("total");

        if (total > 0) {
            JOptionPane.showMessageDialog(this,
                "May " + total + " product(s) pa sa '" + name + "'.\n"
                + "Ilipat o i-archive muna sila bago burahin ang supplier.");
            return;
        }

        try (PreparedStatement del = conn.prepareStatement(deleteSql)) {
            del.setInt(1, id);
            del.executeUpdate();
        }
    }

    loadSuppliers();
    JOptionPane.showMessageDialog(this, "Supplier deleted!");
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}       
    }//GEN-LAST:event_btnNewSupplier1ActionPerformed

