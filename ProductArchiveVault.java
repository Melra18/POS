    private void btnRestore1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRestore1ActionPerformed
    int[] rows = tblArchivedProducts.getSelectedRows();
    if (rows.length == 0) {
        JOptionPane.showMessageDialog(this, "Pumili muna ng product na ibabalik.");
        return;
    }

    String sql = "UPDATE products SET is_archived = 0 WHERE product_id = ?";
    try (Connection conn = ConnectDb.getConnection();
         PreparedStatement ps = conn.prepareStatement(sql)) {

        for (int row : rows) {
            ps.setInt(1, (int) tblArchivedProducts.getValueAt(row, 0));
            ps.addBatch();
        }
        ps.executeBatch();

        loadArchivedProducts();
        inventoryPanel.refreshProductList();
        JOptionPane.showMessageDialog(this, "Product(s) restored.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnRestore1ActionPerformed

    private void btnDelete1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDelete1ActionPerformed
    int[] rows = tblArchivedProducts.getSelectedRows();
    if (rows.length == 0) {
        JOptionPane.showMessageDialog(this, "Pumili muna ng product na buburahin.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this,
        "PERMANENT na buburahin ang " + rows.length + " product(s). Hindi na ito maibabalik.\nSigurado ka ba?",
        "Confirm Delete", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
    if (confirm != JOptionPane.YES_OPTION) return;

    String deleteSql = "DELETE FROM products WHERE product_id = ?";
    int deleted = 0;
    int skipped = 0;

    try (Connection conn = ConnectDb.getConnection();
         PreparedStatement ps = conn.prepareStatement(deleteSql)) {

        for (int row : rows) {
            int id = (int) tblArchivedProducts.getValueAt(row, 0);
            ps.setInt(1, id);
            try {
                deleted += ps.executeUpdate();
            } catch (SQLException e) {
                // may foreign key (ginamit na sa transactions), hindi mabubura
                skipped++;
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        return;
    }

    loadArchivedProducts();
    inventoryPanel.refreshProductList();

    String msg = deleted + " product(s) deleted.";
    if (skipped > 0) {
        msg += "\n" + skipped + " ang hindi nabura dahil may sales record na sila.";
    }
    JOptionPane.showMessageDialog(this, msg);
       
    }//GEN-LAST:event_btnDelete1ActionPerformed
  

