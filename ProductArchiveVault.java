     private void loadArchivedProducts() {
        DefaultTableModel model = (DefaultTableModel) tblArchivedProducts.getModel();
        model.setRowCount(0);

        String sql = "SELECT p.product_id, p.product_name, c.category_name, s.supplier_name, "
                   + "p.unit_price, p.stock_quantity "
                   + "FROM products p "
                   + "LEFT JOIN categories c ON p.category_id = c.category_id "
                   + "LEFT JOIN suppliers s ON p.supplier_id = s.supplier_id "
                   + "WHERE p.is_archived = 1";

        try (Connection conn = ConnectDb.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("product_id"),
                    rs.getString("product_name"),
                    rs.getString("category_name"),
                    rs.getString("supplier_name"),
                    rs.getDouble("unit_price"),
                    rs.getInt("stock_quantity")
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading archived products: " + e.getMessage());
        }
     }

