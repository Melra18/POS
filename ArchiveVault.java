    private void btnRestoreActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRestoreActionPerformed
     int selectedRow = tblArchived.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Please select an employee to restore."
        );
        return;
    }

    String username =
            tblArchived.getValueAt(selectedRow, 0).toString();

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Restore employee '" + username + "'?",
        "Confirm Restore",
        JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql =
            "UPDATE users SET is_archived = 0 WHERE username = ?";

    try (Connection conn = ConnectDb.getConnection();
         PreparedStatement ps = conn.prepareStatement(sql)) {

        ps.setString(1, username);

        int updated = ps.executeUpdate();

        if (updated > 0) {

            JOptionPane.showMessageDialog(
                this,
                "Employee restored successfully!"
            );

            loadArchivedEmployees();
              employeesWindow.refreshEmployeeList();

        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error restoring employee: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }

     // TODO add your handling code here:
    }//GEN-LAST:event_btnRestoreActionPerformed

