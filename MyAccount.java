    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

    String username = Username.getText();
    String currentPassword = new String(CurrentPass.getPassword());
    String newPassword = new String(NewPass.getPassword());
    String confirmPassword = new String(ConfirmPass.getPassword());

    // Check empty fields
    if (currentPassword.isEmpty() ||
        newPassword.isEmpty() ||
        confirmPassword.isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "Please fill in all password fields.",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    // Check if new passwords match
    if (!newPassword.equals(confirmPassword)) {

        JOptionPane.showMessageDialog(
            this,
            "New passwords do not match.",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    try (Connection conn = ConnectDb.getConnection()) {

        // STEP 1: Get the actual password from database
        String checkSql =
            "SELECT password FROM users WHERE username = ?";

        try (PreparedStatement checkStmt =
                 conn.prepareStatement(checkSql)) {

            checkStmt.setString(1, username);

            try (ResultSet rs = checkStmt.executeQuery()) {

                if (!rs.next()) {

                    JOptionPane.showMessageDialog(
                        this,
                        "Username not found.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                    );

                    return;
                }

                String databasePassword = rs.getString("password");

                // STEP 2: Check current password
                if (!currentPassword.equals(databasePassword)) {

                    JOptionPane.showMessageDialog(
                        this,
                        "Current password is incorrect.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                    );

                    return;
                }
            }
        }

        // STEP 3: Update password
        String updateSql =
            "UPDATE users SET password = ? WHERE username = ?";

        try (PreparedStatement updateStmt =
                 conn.prepareStatement(updateSql)) {

            updateStmt.setString(1, newPassword);
            updateStmt.setString(2, username);

            int rowsUpdated = updateStmt.executeUpdate();

            if (rowsUpdated > 0) {

                JOptionPane.showMessageDialog(
                    this,
                    "Password updated successfully!",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE
                );

                dispose();

            } else {

                JOptionPane.showMessageDialog(
                    this,
                    "Password was not updated.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
                );
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database error: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }

  
    }//GEN-LAST:event_jButton2ActionPerformed

